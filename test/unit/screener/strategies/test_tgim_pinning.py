# 5. Trade Manager Exit Evaluation Pinning: Bar 1 Take Profit vs Bar 2 Time Stop
# ==============================================================================


@pytest.mark.tier1
def test_pinning_tgim_exit_logic_pure() -> None:
    """Pins pure exit evaluation: Bar 0 inactive, Bar 1 TP if Close > Close[1], Bar 2 TP or TE."""
    # Bar 0 (Monday): Inactive
    assert (
        evaluate_tgim_exit(
            bars_held=0,
            current_close=Decimal("510.0"),
            previous_close=Decimal("500.0"),
        )
        is None
    )

    # Bar 1 (Tuesday): Take Profit if Close > Prev Close
    assert (
        evaluate_tgim_exit(
            bars_held=1,
            current_close=Decimal("501.0"),
            previous_close=Decimal("500.0"),
        )
        == ExitReason.TAKE_PROFIT
    )
    # Bar 1 (Tuesday): Hold if Close <= Prev Close
    assert (
        evaluate_tgim_exit(
            bars_held=1,
            current_close=Decimal("499.0"),
            previous_close=Decimal("500.0"),
        )
        is None
    )
    assert (
        evaluate_tgim_exit(
            bars_held=1,
            current_close=Decimal("500.0"),
            previous_close=Decimal("500.0"),
        )
        is None
    )

    # Bar 2 (Wednesday): Take Profit if Close > Prev Close
    assert (
        evaluate_tgim_exit(
            bars_held=2,
            current_close=Decimal("501.0"),
            previous_close=Decimal("500.0"),
        )
        == ExitReason.TAKE_PROFIT
    )
    # Bar 2 (Wednesday): Time Stop if Close <= Prev Close
    assert (
        evaluate_tgim_exit(
            bars_held=2,
            current_close=Decimal("499.0"),
            previous_close=Decimal("500.0"),
        )
        == ExitReason.TIME_STOP
    )
    assert (
        evaluate_tgim_exit(
            bars_held=2,
            current_close=Decimal("500.0"),
            previous_close=Decimal("500.0"),
        )
        == ExitReason.TIME_STOP
    )


