@pytest.mark.tier1
def test_pinning_tgim_screener_custom_configuration() -> None:
    """Pins ability to customize parameters via TGIMConfiguration injection."""
    custom_cfg = TGIMConfiguration(
        target_symbol="QQQ",
        lookback_period=45,
        min_premarket_history_bars=1,
    )
    mock_trade_repo = MagicMock(spec=TradeRepository)
    mock_trade_repo.exists.return_value = False
    mock_data_provider = MagicMock(spec=MarketDataProvider)
    df_history = pd.DataFrame(
        [
            {"date": pd.Timestamp("2026-02-05"), "close": 505.0},
            {"date": pd.Timestamp("2026-02-06"), "close": 500.0},
            {"date": pd.Timestamp("2026-02-09"), "close": 490.0},
        ]
    )
    mock_data_provider.get_batch_history.return_value = {"QQQ": df_history}

    screener = TGIMScreener(
        trade_repository=mock_trade_repo,
        data_provider=mock_data_provider,
        configuration=custom_cfg,
    )

    assert screener.configuration.target_symbol == "QQQ"
    assert screener.configuration.lookback_period == 45
    assert screener.configuration.min_premarket_history_bars == 1

    result = screener.run(analysis_date="2026-02-09")
    assert result == 1

    mock_trade_repo.create_trade.assert_called_once()
    assert mock_trade_repo.create_trade.call_args.kwargs["symbol"] == "QQQ"


@pytest.mark.tier1
def test_pinning_tgim_trade_manager_custom_configuration() -> None:
    """Pins ability to customize max holding bars via TGIMConfiguration injection."""
    custom_cfg = TGIMConfiguration(max_holding_bars=3)
    trade_manager = TGIMTradeStrategy(configuration=custom_cfg)

    assert trade_manager.configuration.max_holding_bars == 3

    # At bar 2 (Wednesday), with max_holding_bars=3, holding is not yet exhausted
    assert (
        evaluate_tgim_exit(
            bars_held=2,
            current_close=Decimal("495.0"),
            previous_close=Decimal("500.0"),
            max_holding_bars=trade_manager.configuration.max_holding_bars,
        )
        is None
    )

    # At bar 3 (Thursday), holding is exhausted -> Time Stop
    assert (
        evaluate_tgim_exit(
            bars_held=3,
            current_close=Decimal("495.0"),
            previous_close=Decimal("500.0"),
            max_holding_bars=trade_manager.configuration.max_holding_bars,
        )
        == ExitReason.TIME_STOP
    )
