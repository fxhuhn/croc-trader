# 4. Position Sizing Pinning: Floor Quantity Calculation
# ==============================================================================


@pytest.mark.tier1
def test_pinning_tgim_position_quantity() -> None:
    """Pins strict floor rounding for TGIM position sizing."""
    assert calculate_tgim_position_quantity(Decimal("10000.0"), Decimal("500.0")) == 20
    # 10000 / 499 = 20.04008 -> 20 shares
    assert calculate_tgim_position_quantity(Decimal("10000.0"), Decimal("499.0")) == 20
    # 10000 / 501 = 19.96 -> 19 shares
    assert calculate_tgim_position_quantity(Decimal("10000.0"), Decimal("501.0")) == 19
    # Edge conditions
    assert calculate_tgim_position_quantity(Decimal("0.0"), Decimal("500.0")) == 0
    assert calculate_tgim_position_quantity(Decimal("10000.0"), Decimal("0.0")) == 0
    assert calculate_tgim_position_quantity(Decimal("-100.0"), Decimal("500.0")) == 0


