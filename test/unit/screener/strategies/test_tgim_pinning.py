# 2. Pure Calculation Pinning: Setup Evaluation Logic
# ==============================================================================


@pytest.mark.tier1
def test_pinning_tgim_setup_formula_and_trigger() -> None:
    """Pins Monday Close < min(Friday Close, Thursday Close) setup rule."""
    # Case 1: Triggered (Monday 495 < min(500, 505) = 500)
    res_triggered = evaluate_tgim_setup(
        current_close=Decimal("495.00"),
        friday_close=Decimal("500.00"),
        thursday_close=Decimal("505.00"),
    )
    assert res_triggered.is_signal is True
    assert res_triggered.threshold_price == Decimal("500.00")
    assert res_triggered.setup_close == Decimal("495.00")

    # Case 2: Rejected because Close >= min (Monday 500 == Friday 500)
    res_equal = evaluate_tgim_setup(
        current_close=Decimal("500.00"),
        friday_close=Decimal("500.00"),
        thursday_close=Decimal("505.00"),
    )
    assert res_equal.is_signal is False

    # Case 3: Rejected because Close > min (Monday 502 > Friday 500)
    res_higher = evaluate_tgim_setup(
        current_close=Decimal("502.00"),
        friday_close=Decimal("500.00"),
        thursday_close=Decimal("505.00"),
    )
    assert res_higher.is_signal is False

    # Case 4: Thursday is lower than Friday
    res_thursday_lower = evaluate_tgim_setup(
        current_close=Decimal("485.00"),
        friday_close=Decimal("500.00"),
        thursday_close=Decimal("490.00"),
    )
    assert res_thursday_lower.is_signal is True
    assert res_thursday_lower.threshold_price == Decimal("490.00")


